# Task 4: Age Converter (Intermediate)
age_years = int(input("Enter your age in years: "))
age_months = age_years * 12
age_days = age_years * 365
age_hours = age_years * 365 * 24
print("\nYour age in months is:", age_months)
print("Your age in days is:", age_days)
print("Your age in hours is:", age_hours)
